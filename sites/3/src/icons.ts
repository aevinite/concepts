const CLS: Record<string, string> = { "#": "i-ink", ".": "i-pap", g: "i-g", a: "i-a" };

const cache = new Map<string, string>();

/** SVG markup for a pixel icon, `size` CSS px square. */
export function icon(name: string, size = 48, label = ""): string {
  const key = `${name}:${size}`;
  let body = cache.get(key);
  if (!body) {
    const map = MAPS[name] ?? MAPS.doc;
    const rects: string[] = [];
    map.forEach((rowRaw, y) => {
      const row = rowRaw.padEnd(16, " ").slice(0, 16);
      let x = 0;
      while (x < 16) {
        const c = row[x];
        if (c === " ") { x++; continue; }
        let run = 1;
        while (x + run < 16 && row[x + run] === c) run++;
        rects.push(`<rect class="${CLS[c] ?? "i-ink"}" x="${x}" y="${y}" width="${run}" height="1"/>`);
        x += run;
      }
    });
    body = rects.join("");
    cache.set(key, body);
  }
  const a11y = label ? `role="img" aria-label="${label}"` : `aria-hidden="true"`;
  return `<svg class="px" ${a11y} width="${size}" height="${size}" viewBox="0 0 16 16" shape-rendering="crispEdges">${body}</svg>`;
}

